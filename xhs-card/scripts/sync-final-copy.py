#!/usr/bin/env python3
"""Synchronize user-locked UTF-8 copy without rewriting it. No model/network calls."""
import argparse
import hashlib
import html
import json
from pathlib import Path
import re
import tempfile
import zipfile


def local_path(project, value):
    path = (project / value).resolve()
    if not path.is_relative_to(project):
        raise ValueError('Output paths must stay inside the project')
    return path


def digest(data):
    return hashlib.sha256(data).hexdigest()


def atomic_write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as f:
        temp = Path(f.name)
        f.write(data)
    temp.replace(path)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', required=True, type=Path)
    parser.add_argument('--project', required=True, type=Path)
    parser.add_argument('--text-name', default='小红书最终正文.txt')
    parser.add_argument('--archive', required=True)
    args = parser.parse_args()
    project = args.project.resolve()
    if not project.is_dir():
        raise ValueError('Project directory does not exist')
    raw = args.source.read_bytes()
    text = raw.decode('utf-8')  # Do not strip, normalize, rewrite, or add a newline.
    target = local_path(project, args.text_name)
    archive = local_path(project, args.archive)
    index = project / 'index.html'
    generator = project / 'preview.cjs'
    pattern = re.compile(r'(<textarea\b(?=[^>]*\bid=["\']postText["\'])[^>]*>).*?(</textarea>)', re.S)
    updates = {}
    for path in (index, generator):
        if not path.exists():
            continue
        escaped = html.escape(text)
        if path == generator:
            escaped = escaped.replace('\\', '\\\\').replace('`', '\\`').replace('${', '\\${')
        content, count = pattern.subn(lambda m: m[1] + escaped + m[2], path.read_text())
        if count != 1:
            raise ValueError(f'{path.name}: expected one textarea#postText; no files changed')
        updates[path] = content.encode('utf-8')
    if not index.exists():
        raise ValueError('Expected index.html with textarea#postText; adapt the page first')
    before = {p.name: digest(p.read_bytes()) for p in sorted((project / '高清图片').glob('*.png'))}
    # Prepare the package before changing files. Preserve unrelated members of an existing ZIP.
    archive.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=archive.parent, suffix='.zip', delete=False) as f:
        temporary_zip = Path(f.name)
    try:
        with zipfile.ZipFile(temporary_zip, 'w', zipfile.ZIP_DEFLATED) as out:
            if archive.exists():
                with zipfile.ZipFile(archive) as old:
                    for item in old.infolist():
                        if item.filename != args.text_name:
                            out.writestr(item, old.read(item.filename))
            else:
                for image in sorted((project / '高清图片').glob('*.png')):
                    out.write(image, image.relative_to(project))
            out.writestr(args.text_name, raw)
        with zipfile.ZipFile(temporary_zip) as test:
            assert test.read(args.text_name) == raw
            assert test.testzip() is None
        if target.exists() and target.read_bytes() != raw:
            backup = project / '文案历史' / ('before-verbatim-' + digest(target.read_bytes())[:12] + '.txt')
            if not backup.exists():
                atomic_write(backup, target.read_bytes())
        atomic_write(target, raw)
        for path, data in updates.items():
            atomic_write(path, data)
        temporary_zip.replace(archive)
    finally:
        temporary_zip.unlink(missing_ok=True)
    assert target.read_bytes() == raw
    shown = re.search(r'<textarea\b(?=[^>]*\bid=["\']postText["\'])[^>]*>(.*?)</textarea>', index.read_text(), re.S)
    assert html.unescape(shown[1]) == text
    after = {p.name: digest(p.read_bytes()) for p in sorted((project / '高清图片').glob('*.png'))}
    assert before == after
    with zipfile.ZipFile(archive) as package:
        assert package.read(args.text_name) == raw
    report = {'mode': 'verbatim', 'sha256': digest(raw), 'bytes': len(raw),
              'text': args.text_name, 'archive': args.archive, 'imagesUnchanged': True,
              'imageSHA256': after, 'previewTextMatches': True,
              'previewScreenshot': 'Refresh separately if required; screenshots are not regenerated by this script.'}
    atomic_write(project / '正文锁定校验.json', json.dumps(report, ensure_ascii=False, indent=2).encode())
    print(json.dumps({'mode': 'verbatim', 'bytes': len(raw), 'sha256': digest(raw), 'imagesUnchanged': True}))


if __name__ == '__main__':
    main()
